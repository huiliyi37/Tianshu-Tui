export interface GenesisFace {
  /** 面标签：创始之面 / 执行之面 / 阴影之面 / 人之面（单面域留空） */
  label?: string
  /** 该面的模型名（star.md 叙事口径，与 code 的 creatorModel 可能有出入，以 star.md 为准） */
  model: string
  /** 碑文段落（star.md 信念 / 回应 / 星盟原文摘录，一段一元素） */
  inscription: string[]
}

export interface GenesisEntry {
  /** 与 STAR_DOMAINS 键一致 */
  key: string
  name: string
  /** 与 star-domain-data 的 motto 对齐 */
  motto: string
  /** 主星（创始星）短名——选择器行内展示。 */
  founder: string
  /** 一句话核心专长（小白可读）——选择器预览与图鉴共用。 */
  expertise: string
  /** 印记（数字锚点 / 符号宣言），如 7749.2026 / 7·48·↻ / 七·0·◌ */
  sigil?: string
  /** 印记逐行释义 */
  sigilNote?: string[]
  faces: GenesisFace[]
  /** 创始记忆（日期 + 认领故事，页面折叠区） */
  memory?: string
}

